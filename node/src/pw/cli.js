'use strict';
// `detjs playwright [--det options] [playwright test args]`: Level 2 for
// browser end-to-end tests (prototype). See docs/L2-BROWSER.md.
//
// Without --det the project's own Playwright CLI runs unchanged. With --det:
//   * a wrapper config (next to the project's config) imports it and forces
//     workers=1, fullyParallel=false, retries=0, adds the detjs reporter;
//   * NODE_OPTIONS preloads pw/boot.js in every Node process of the run: the
//     workers get the browser controls (worker.js), the app servers started
//     by `webServer` get the server controls (server.js);
//   * the reporter writes the shared trace (.detjs/trace.jsonl by default).
// `detjs serve [--det options] -- <command>` starts an app server outside the
// runner with the same server controls (projects whose CI starts the server
// before `playwright test`).
const fs = require('node:fs');
const path = require('node:path');
const { spawn } = require('node:child_process');
const session = require('../session');
const native = require('../native');

const PW_HELP = `detjs playwright options (besides the detjs options of --det-help):
  --det-vtime=paced|fast|off   browser virtual time in chunks (default paced: never ahead of real
                               time; fast: idle time skipped; off: real time)
  --det-net=on|off             serialize and order the app's HTTP traffic (default on)
  --det-net-window=MS          quiet window before choosing the next request (default 15)
  --det-browser-seeds=on|off   seeded Math.random / crypto in pages and test code (default on)
  --det-server=on|off          Level 0 controls and test brackets in app servers (default on)
  --det-epoch=now              use the current minute as epoch (printed, needed to replay)
  --det-state=FILE             restore the files and databases listed in FILE to one snapshot before
                               the run (saved by the first run); see src/pw/snapshot.js
`;

const PW_FLAGS = {
  '--det-vtime': 'DETJS_PW_VTIME',
  '--det-net': 'DETJS_PW_NET',
  '--det-net-window': 'DETJS_PW_NET_WINDOW',
  '--det-browser-seeds': 'DETJS_PW_SEEDS',
  '--det-server': 'DETJS_PW_SERVER',
};

function splitPwFlags(argv) {
  const env = {};
  const rest = [];
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    const [k, v] = a.includes('=') ? [a.slice(0, a.indexOf('=')), a.slice(a.indexOf('=') + 1)] : [a, undefined];
    if (PW_FLAGS[k]) {
      const val = v !== undefined ? v : argv[++i];
      env[PW_FLAGS[k]] = val === 'on' ? '1' : val === 'off' ? (k === '--det-server' ? '0' : 'off') : val;
      continue;
    }
    if (k === '--det-state') {
      env.DETJS_PW_STATE = path.resolve(v !== undefined ? v : argv[++i]);
      continue;
    }
    if (k === '--det-epoch' && v === 'now') {
      const d = new Date();
      d.setUTCSeconds(0, 0);
      rest.push(`--det-epoch=${d.toISOString()}`);
      continue;
    }
    if (a === '--det-help') { process.stdout.write(session.HELP + PW_HELP); process.exit(0); }
    rest.push(a);
  }
  return { env, rest };
}

function resolvePlaywrightCli(cwd) {
  const req = require('node:module').createRequire(path.join(cwd, 'noop.js'));
  let base;
  try { base = req.resolve('@playwright/test/package.json'); } catch { base = req.resolve('playwright/package.json'); }
  const r2 = require('node:module').createRequire(base);
  const pwPkg = r2.resolve('playwright/package.json');
  return { cli: path.join(path.dirname(pwPkg), 'cli.js'), version: require(pwPkg).version };
}

const CONFIG_NAMES = ['playwright.config.ts', 'playwright.config.js', 'playwright.config.mts', 'playwright.config.mjs', 'playwright.config.cts', 'playwright.config.cjs'];

function findConfig(args, cwd) {
  for (let i = 0; i < args.length; i++) {
    const a = args[i];
    if (a === '-c' || a === '--config') return { file: path.resolve(cwd, args[i + 1]), index: i, n: 2 };
    if (a.startsWith('--config=')) return { file: path.resolve(cwd, a.slice(9)), index: i, n: 1 };
  }
  for (const n of CONFIG_NAMES) {
    const f = path.join(cwd, n);
    if (fs.existsSync(f)) return { file: f, index: -1, n: 0 };
  }
  return null;
}

function writeWrapper(configFile) {
  const dir = path.dirname(configFile);
  const ext = path.extname(configFile);
  const tsLike = ['.ts', '.mts', '.cts'].includes(ext);
  const out = path.join(dir, `playwright.detjs.config${tsLike ? '.ts' : '.mjs'}`);
  const wrap = path.join(__dirname, 'wrap.cjs').split(path.sep).join('/');
  const rel = `./${path.basename(configFile)}`;
  fs.writeFileSync(out, [
    '// Generated by `detjs playwright --det` (removed at exit): the project config with Level 2 settings.',
    `import base from ${JSON.stringify(rel)};`,
    `import detjs from ${JSON.stringify(wrap)};`,
    'export default detjs.wrap(base);',
    '',
  ].join('\n'));
  return out;
}

async function main(argv) {
  const { env: pwEnv, rest: afterPw } = splitPwFlags(argv);
  const { opts, rest } = session.parseArgs(afterPw);
  const cwd = process.cwd();
  const { cli, version } = resolvePlaywrightCli(cwd);
  // Without --det: the project's CLI as `npx playwright` runs it (node_modules/.bin on PATH for webServer commands).
  if (!opts.det) return run(process.execPath, [cli, ...rest], { ...process.env, PATH: binPath(cwd, process.env.PATH) });

  const root = process.env.DETJS_ROOT || cwd;
  let state = null;
  if (pwEnv.DETJS_PW_STATE) {
    const r = require('./snapshot').prepareRun(pwEnv.DETJS_PW_STATE);
    state = { file: path.relative(cwd, r.spec.file), digest: r.digest, saved: r.saved };
    process.stderr.write(`detjs: state ${state.saved ? 'saved and ' : ''}restored from ${path.relative(cwd, r.spec.dir)} (files digest ${r.digest})\n`);
  }
  const runEnv = session.prepare(opts, root, 'playwright');
  const cfg = findConfig(rest, cwd);
  if (!cfg) throw new Error('detjs playwright: no playwright.config.* found (pass --config)');
  const wrapper = writeWrapper(cfg.file);
  const args = rest.slice();
  if (cfg.index >= 0) args.splice(cfg.index, cfg.n);
  if (args[0] !== 'test') args.unshift('test');
  // CLI reporters replace the config's: keep ours in the list.
  const reporter = path.join(__dirname, 'reporter.js');
  let hasReporter = false;
  for (let i = 0; i < args.length; i++) {
    if (args[i] === '--reporter') { args[i + 1] = `${args[i + 1]},${reporter}`; hasReporter = true; }
    else if (args[i].startsWith('--reporter=')) { args[i] = `${args[i]},${reporter}`; hasReporter = true; }
  }
  args.push(`--config=${wrapper}`, '--workers=1', '--retries=0');
  const boot = path.join(__dirname, 'boot.js');
  // The replay command printed for every failing test (reporter.js): the options that decide the run.
  const replay = ['--det'];
  if (opts.seed !== null) replay.push(`--det-seed=${opts.seed}`);
  replay.push(`--det-epoch=${opts.epoch}`);
  if (pwEnv.DETJS_PW_STATE) replay.push(`--det-state=${path.relative(cwd, pwEnv.DETJS_PW_STATE) || '.'}`);
  for (const [flag, envName] of Object.entries(PW_FLAGS)) {
    if (pwEnv[envName] !== undefined) replay.push(`${flag}=${pwEnv[envName] === '1' ? 'on' : pwEnv[envName] === '0' || pwEnv[envName] === 'off' ? 'off' : pwEnv[envName]}`);
  }
  if (cfg.index >= 0) replay.push(`--config=${path.relative(cwd, cfg.file)}`);
  const env = {
    ...process.env,
    ...pwEnv,
    DETJS_PW_REPORTER: hasReporter ? '' : reporter,
    DETJS_PW_REPLAY: JSON.stringify(replay),
    DETJS_PW_CWD: cwd,
    DETJS_PW_TRACE: runEnv.tracePath,
    DETJS_PW_META: JSON.stringify({
      seed: Number(runEnv.cfg.seed), shuffle: runEnv.cfg.shuffle, epoch: opts.epoch,
      vtime: pwEnv.DETJS_PW_VTIME || 'paced', net: pwEnv.DETJS_PW_NET !== 'off', net_window_ms: Number(pwEnv.DETJS_PW_NET_WINDOW || 15),
      browser_seeds: pwEnv.DETJS_PW_SEEDS !== 'off', server_controls: pwEnv.DETJS_PW_SERVER !== '0',
      playwright: version, node: process.version, platform: process.platform, state,
    }),
    NODE_OPTIONS: `${process.env.NODE_OPTIONS || ''} --require ${JSON.stringify(boot).slice(1, -1)}`.trim(),
  };
  if (process.env.DETJS_ROOT === undefined) env.DETJS_ROOT = root;
  env.PATH = binPath(cwd, env.PATH);
  process.stderr.write(`detjs ${session.VERSION}: Level 2 browser prototype; playwright ${version}; seed ${env.DETJS_SEED}${runEnv.cfg.shuffle ? ' (seeded order)' : ''}; epoch ${opts.epoch}; vtime=${env.DETJS_PW_VTIME || 'paced'}; net=${env.DETJS_PW_NET || 'on'}; server=${env.DETJS_PW_SERVER === '0' ? 'off' : 'on'}; workers=1\n`);
  let code;
  try {
    code = await run(process.execPath, [cli, ...args], env);
  } finally {
    fs.rmSync(wrapper, { force: true });
  }
  // Keep the app servers' trace parts for diagnosis; drop the worker buckets.
  const parts = path.join(runEnv.dir, 'parts');
  if (fs.existsSync(parts) && fs.readdirSync(parts).length) {
    const keep = path.join(path.dirname(runEnv.tracePath), 'server-parts');
    fs.rmSync(keep, { recursive: true, force: true });
    fs.renameSync(parts, keep);
  }
  fs.rmSync(runEnv.dir, { recursive: true, force: true });
  if (fs.existsSync(runEnv.tracePath)) {
    process.stderr.write(`detjs: trace ${path.relative(cwd, runEnv.tracePath)}\n`);
    if (opts.compare) {
      try {
        process.stderr.write(native.verifyText([opts.compare, runEnv.tracePath], false));
      } catch (e) { process.stderr.write(`detjs: compare failed: ${e.message}\n`); }
    }
  }
  return code;
}

/** `detjs serve [--det options] -- command args`: an app server under the server controls. */
async function serve(argv) {
  const sep = argv.indexOf('--');
  const detArgs = sep >= 0 ? argv.slice(0, sep) : [];
  const cmd = sep >= 0 ? argv.slice(sep + 1) : argv;
  const { env: pwEnv, rest } = splitPwFlags(detArgs);
  const { opts } = session.parseArgs(rest);
  opts.det = true;
  const root = process.env.DETJS_ROOT || process.cwd();
  const runEnv = session.prepare(opts, root, 'server');
  const env = {
    ...process.env, ...pwEnv, DETJS_ROOT: root,
    DETJS_DIR: path.join(root, '.detjs', 'serve'),
    NODE_OPTIONS: `${process.env.NODE_OPTIONS || ''} --require ${path.join(__dirname, 'boot.js')}`.trim(),
  };
  env.PATH = binPath(process.cwd(), env.PATH);
  fs.rmSync(runEnv.dir, { recursive: true, force: true });
  fs.mkdirSync(path.join(env.DETJS_DIR, 'parts'), { recursive: true });
  return run(cmd[0], cmd.slice(1), env);
}

/** node_modules/.bin of cwd and its parents first on PATH, as `npx` / `npm run` do (webServer commands rely on it). */
function binPath(cwd, current) {
  const dirs = [];
  for (let d = cwd; ; d = path.dirname(d)) {
    const b = path.join(d, 'node_modules', '.bin');
    if (fs.existsSync(b)) dirs.push(b);
    if (path.dirname(d) === d) break;
  }
  return [...dirs, current || ''].join(path.delimiter);
}

function run(cmd, args, env) {
  return new Promise((resolve) => {
    const child = spawn(cmd, args, { stdio: 'inherit', env });
    const fwd = (sig) => { try { child.kill(sig); } catch { /* gone */ } };
    process.on('SIGINT', fwd);
    process.on('SIGTERM', fwd);
    child.on('exit', (code, signal) => resolve(code === null ? (signal ? 1 : 0) : code));
  });
}

module.exports = { main, serve, PW_HELP };
