#!/usr/bin/env python3
"""C5.3 step 2.10: REPORT.md's generated part, from the committed rows only (re-runnable by anyone).

Usage: report.py   writes REPORT.md: the hand-written part above the marker line is kept, the rest regenerated.
"""
from __future__ import annotations

import json
import sys
from collections import Counter
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import rules as R  # noqa: E402
from collect import MAX_REPOS, MAX_REQUESTS, read_jsonl  # noqa: E402
from select_repos import MIN_COUNT  # noqa: E402

MARK = "<!-- generated by report.py below this line -->"


def _read(p: Path):
    return json.loads(p.read_text()) if p.exists() else None


def generate(res: Path, selected: dict | None, handcheck: list[dict]) -> str:
    windows = read_jsonl(res / "pool_windows.jsonl")
    pool = read_jsonl(res / "pool.jsonl.gz")
    rows = read_jsonl(res / "prs.jsonl.gz")
    state = _read(res / "checkpoint.json") or {}
    chunks = read_jsonl(res / "chunks.jsonl")
    oracle = read_jsonl(res / "oracle.jsonl")
    L = [MARK, "", "## Requests and stop", ""]
    L.append(f"- Collection requests (2.3-2.6, cap {MAX_REQUESTS:,}, metadata and log blobs included): {state.get('requests', 0)}")
    L.append(f"- Oracle requests (2.8): {state.get('oracle_requests', 0)}")
    L.append(f"- Stop reason: {state.get('stopped')}; repositories read: {state.get('repos_read', 0)} (cap {MAX_REPOS})")
    L.append(f"- Chunks: {len(chunks)} ({', '.join(c['chunk'] + ': ' + str(c['stop']) for c in chunks)})")
    L += ["", "## Pool (2.2)", ""]
    if windows:
        L.append(f"D = {windows[0]['D']}; {len(windows)} (family, window) queries; pool after family rules and URL "
                 f"de-duplication: {len(pool)} PRs.")
        L += ["", "| Family | Search results read | In pool (first family) | Truncated windows |", "|---|---|---|---|"]
        first = Counter(r["family"] for r in pool)
        for f in R.FAMILIES:
            ws = [w for w in windows if w["family"] == f]
            tr = [w["window"] for w in ws if w["truncated"]]
            L.append(f"| {f} | {sum(w['rows'] for w in ws)} | {first[f]} | {len(tr)} {', '.join(tr)} |")
    owner = sum(R.owner_excluded(r["repo"]) for r in pool)
    L += ["", "## Exclusions", "", f"- Pool PRs of excluded owners (no request): {owner}"]
    rep = Counter(v.get("reason") for v in (state.get("repos") or {}).values() if v.get("status") == "excluded")
    L.append(f"- Repositories excluded from metadata: {dict(sorted(rep.items())) or 'none'}")
    verd = Counter(r["verdict"] for r in rows)
    L.append(f"- PR verdicts (every PR row): {dict(sorted(verd.items()))}")
    reads = [r for r in rows if r["verdict"] != "repo_too_young"]
    qual = list({r["url"]: r for r in rows if r["verdict"] == "qualifying"}.values())
    L += ["", "## PRs read", "",
          f"- PRs read: {len(reads)}; qualifying: {len(qual)}; per runner: "
          f"{dict(sorted(Counter(r['runner'] for r in qual).items()))}"]
    cand = [c for r in rows for c in r.get("candidates") or []]
    L.append(f"- Candidate job logs read: {len(cand)}; API status {dict(Counter(str(c['api_status']) for c in cand))}; "
             f"blob status {dict(Counter(str(c['blob_status']) for c in cand))}; detected "
             f"{dict(Counter(str(c['runner']) for c in cand))}")
    L += ["", "## Selected repositories (2.7)", ""]
    if selected:
        L.append(f"{selected['n_selected']} selected of {selected['n_eligible']} repositories with >= {MIN_COUNT} qualifying PRs."
                 + ("" if selected["reaches_6"] else " **Fewer than 6: C5 cannot reach 6 repositories; the coordinator "
                                                     "decides (window and threshold unchanged).**"))
        for s in selected["repositories"]:
            L += ["", f"### {s['full_name']} (count {s['count']}; runners {', '.join(s['runners'])}; families "
                      f"{', '.join(s['families'])})", ""]
            L += [f"- {p['url']} B0 `{p['B0']}` job {p['job_id']} `{p['job_name']}` ({p['runner']})" for p in s["prs"]]
        sel_urls = {p["url"] for s in selected["repositories"] for p in s["prs"]}
        feats = [r["features"] for r in qual if r["url"] in sel_urls]
        L += ["", "## Job features of the selected PRs (2.6)", ""]
        if feats:
            L.append(f"- with services: {sum(bool(f['services']) for f in feats)} of {len(feats)}; images: "
                     f"{dict(Counter(i for f in feats if isinstance(f['services'], dict) for i in f['services'].values()))}")
            L.append(f"- with a matrix: {sum(f['matrix'] is not None for f in feats)}; container: "
                     f"{sum(f['container'] for f in feats)}; with needs: {sum(bool(f['needs']) for f in feats)}; "
                     f"uses secrets or vars: {sum(f['uses_secrets'] for f in feats)}")
            L.append(f"- runs-on: {dict(Counter(json.dumps(f['runs_on']) for f in feats))}")
            dif = Counter(str(r.get('differs_at_head')) for r in qual if r['url'] in sel_urls)
            L.append(f"- job definition differs between head and B0: {dict(dif)}")
        L += ["", "## Oracle coverage (2.8)", ""]
        if oracle:
            has = sum(o["has_job"] for o in oracle)
            L.append(f"- Selected PRs with a completed push run of the same workflow at B0 and a job of the same name: "
                     f"{has} of {len(oracle)} ({100 * has / len(oracle):.0f}%); conclusions "
                     f"{dict(Counter(o.get('conclusion') for o in oracle if o['has_job']))}; other statuses "
                     f"{dict(Counter(o['status'] for o in oracle if not o['has_job']))}")
        else:
            L.append("- not collected yet")
    else:
        L.append("not selected yet")
    L += ["", "## Hand check (2.11)", ""]
    if handcheck:
        agree = sum(h["agrees"] for h in handcheck)
        L.append(f"- {agree} of {len(handcheck)} sampled qualifying jobs agree with 2.5 (seed "
                 f"{handcheck[0].get('seed', 4)}). Excerpts exist only for matched jobs: the hand check finds false "
                 "matches, not misses.")
        L += [f"- job {h['job_id']}: seen {h['seen_runner']}, agrees {h['agrees']}. {h.get('note', '')}".rstrip()
              for h in handcheck]
    else:
        L.append("- not done yet")
    return "\n".join(L) + "\n"


def screen_summary(res: Path) -> str:
    rows = read_jsonl(res / "screen.jsonl")
    state = _read(res / "checkpoint.json") or {}
    v = Counter(r["verdict"] for r in rows)
    rule = Counter(w["rule"] for r in rows if r["verdict"] == "eligible" for w in r.get("workflows") or [])
    return (f"## Screening (R2.2)\n\n- Candidate repositories screened: {len(rows)} (GraphQL requests: "
            f"{state.get('graphql_requests', 0)}); verdicts {dict(sorted(v.items()))}\n- Eligible repositories' matching "
            f"workflow files by rule: {dict(sorted(rule.items()))}\n\n")


def main(argv: list[str] | None = None) -> int:
    """report.py: REPORT.md (rev 1). report.py --r2: REPORT_R2.md (rev 2, results_r2/)."""
    r2 = "--r2" in (argv if argv is not None else sys.argv[1:])
    out = HERE / ("REPORT_R2.md" if r2 else "REPORT.md")
    head = out.read_text().split(MARK, 1)[0] if out.exists() else "# C5.3 report\n\n"
    if r2:
        res = HERE / "results_r2"
        hc = read_jsonl(HERE / "handcheck_r2.jsonl")
        body = generate(res, _read(HERE / "selected_r2.json"), hc).replace(MARK + "\n", MARK + "\n\n" + screen_summary(res), 1)
    else:
        body = generate(HERE / "results", _read(HERE / "selected.json"), read_jsonl(HERE / "handcheck.jsonl"))
    out.write_text(head.rstrip("\n") + "\n\n" + body)
    print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
