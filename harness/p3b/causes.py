#!/usr/bin/env python3
"""P3b step C1: the ARTIFACT rows of the annotated rows.jsonl, grouped by cause (P3's label, unchanged), with one
minimal reproduction per cause and P3's comparable rows -> CAUSES.md. Proposes no owner: the owner column is filled
from data/owners.json, which records the owner the coordinator named for each cause (empty until then).

    python3 harness/p3b/causes.py [--p3-ref origin/claude/p3-flips]

P3's rows (gate rev 3 note 3): read from P3's latest rows.jsonl (`git show <p3-ref>:harness/p3_flips/rows.jsonl`);
per cause, P3's rows with the same reason, and every P3 row whose first --det line is a timeout, whatever its cause.
"""
from __future__ import annotations

import argparse
import json
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import classify  # noqa: E402
import timeouts  # noqa: E402

OUT = os.path.join(HERE, "CAUSES.md")
OWNERS = os.path.join(classify.DATA, "owners.json")
SPECS = os.path.join(HERE, "..", "parallel_measure", "specs.json")
STEPS = ["L1", "L2a", "L2b", "L3", "L4", "L5", "L6", "L7"]
STEP_FLAGS = {"L1": "--det-timers=real"}


def p3_rows(ref):
    try:
        sha = subprocess.run(["git", "rev-parse", ref], capture_output=True, text=True, check=True, cwd=HERE).stdout.strip()
        txt = subprocess.run(["git", "show", f"{ref}:harness/p3_flips/rows.jsonl"], capture_output=True, text=True,
                             check=True, cwd=HERE).stdout
    except (subprocess.CalledProcessError, OSError) as e:
        return None, [], f"P3 rows not readable at {ref}: {e}"
    return sha, [json.loads(x) for x in txt.splitlines() if x.strip()], None


def reproduction(row, commit):
    """The smallest set, a failing --det command and the command that clears it, from the row's own records."""
    lad = row.get("ladder") or {}
    step = row.get("clears_at")
    rep = {"repo": row["repo"], "commit": commit, "test_id": row["test_id"], "set": row.get("set"),
           "first_failure": timeouts.first_line(row.get("det_failure"))}
    if step == "wrapper":
        rep["fails"] = lad["L7"]["runs"][0]["cmd"]
        rep["fails_note"] = "L7 (every control off) still reproduces"
        rep["clears"] = (row.get("control") or {}).get("runs", [{}])[0].get("cmd")
        rep["clears_note"] = "the plain control (no detjs)"
        if row.get("timeout_wall"):
            tw = row["timeout_wall"]
            rep["walls"] = {"plain": tw["plain_walls"], "l7": tw["l7_walls"]}
        return rep
    i = STEPS.index(step)
    rep["clears"] = lad[step]["runs"][0]["cmd"]
    rep["clears_note"] = f"ladder {step}"
    if i > 0 and STEPS[i - 1] in lad:
        rep["fails"] = lad[STEPS[i - 1]]["runs"][0]["cmd"]
        rep["fails_note"] = f"ladder {STEPS[i - 1]} (recorded, reproduced)"
    else:
        flag = STEP_FLAGS.get(step, "")
        rep["fails"] = rep["clears"].replace(" " + flag, "") if flag else rep["clears"]
        rep["fails_note"] = f"the {step} command without `{flag}` (the set's --det run; alone runs reproduced)"
    return rep


def group(rows):
    g = {}
    for r in rows:
        if r["verdict"] == "ARTIFACT":
            g.setdefault(r["reason"], []).append(r)
    for k in g:
        g[k].sort(key=lambda r: (r["repo"], r["test_id"]))
    return dict(sorted(g.items()))


def p3_comparable(reason, p3):
    same = [r for r in p3 if r.get("reason") == reason]
    tmo = [r for r in p3 if timeouts.is_timeout(r) and r.get("reason") != reason]
    return same, tmo


def render(rows, p3sha, p3, p3err, owners, commits):
    out = ["# P3b ARTIFACT causes (generated by `harness/p3b/causes.py` from the annotated `rows.jsonl`)", "",
           "Cause labels are P3's `classify.py` labels, unchanged. P3b names no owner: the owner column is the one the "
           "coordinator named (`data/owners.json`).", "",
           f"P3 rows compared: `harness/p3_flips/rows.jsonl` at {p3sha or '-'}" + (f" ({p3err})" if p3err else ""), "",
           "| cause | cases | of which timeout | engine_overhead true | over_budget true | owner (coordinator) |",
           "|---|---|---|---|---|---|"]
    groups = group(rows)
    for reason, rr in groups.items():
        t = [r for r in rr if timeouts.is_timeout(r)]
        eo = sum(1 for r in t if (r.get("overhead") or {}).get("engine_overhead"))
        ob = sum(1 for r in t if (r.get("overhead") or {}).get("over_budget"))
        out.append(f"| {reason} | {len(rr)} | {len(t)} | {eo} | {ob} | {owners.get(reason, 'not named yet')} |")
    for reason, rr in groups.items():
        out += ["", f"## {reason}", "", "| repository | test id | first --det line | overhead (ratio, over_budget, "
                "engine_overhead) |", "|---|---|---|---|"]
        for r in rr:
            ov = r.get("overhead")
            ovs = f"{ov['ratio']}, {ov['over_budget']}, {ov['engine_overhead']}" if ov else "-"
            fl = (timeouts.first_line(r.get("det_failure")) or "-").replace("|", "/")[:160]
            out.append(f"| {r['repo']} | `{r['test_id'].replace('|', '/')}` | {fl} | {ovs} |")
        rep = reproduction(rr[0], commits.get(rr[0]["repo"]))
        out += ["", "Minimal reproduction:", "", f"- repository {rep['repo']} at {rep['commit']}, case `{rep['test_id']}`",
                f"- set: {json.dumps(rep['set'])}", f"- first failure line: `{rep['first_failure']}`",
                f"- fails ({rep['fails_note']}): `{rep['fails']}`", f"- clears ({rep['clears_note']}): `{rep['clears']}`"]
        if rep.get("walls"):
            out.append(f"- walls (s): plain {rep['walls']['plain']}, L7 {rep['walls']['l7']}")
        same, tmo = p3_comparable(reason, p3)
        out += ["", f"P3 rows with the same label: {len(same)}"]
        out += [f"- {r['repo']} `{r['test_id']}`" for r in same]
        out += ["", f"P3 rows whose first --det line is a timeout (other causes): {len(tmo)}"]
        out += [f"- {r['repo']} `{r['test_id']}`: {r['verdict']} {r['reason']}" for r in tmo]
    return "\n".join(out) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--p3-ref", default="origin/claude/p3-flips")
    o = ap.parse_args()
    rows = classify.load_rows()
    sha, p3, err = p3_rows(o.p3_ref)
    owners = json.load(open(OWNERS)) if os.path.exists(OWNERS) else {}
    specs = json.load(open(SPECS))
    commits = {r: specs[r]["commit"] for r in {x["repo"] for x in rows} if r in specs}
    with open(OUT, "w") as f:
        f.write(render(rows, sha, p3, err, owners, commits))
    print(f"-> {OUT}")


if __name__ == "__main__":
    main()
