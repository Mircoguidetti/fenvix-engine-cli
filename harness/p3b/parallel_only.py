#!/usr/bin/env python3
"""P3b step B4: the parallel-only cases (count_extra.json's `parallel_only`: failed in a w4 --det run, passed in both
plain runs and both w1 --det runs) -> harness/p3b/PARALLEL-ONLY.md. Not classified, only listed and routed. Per case:
test id, file, the two w4 outcomes, the first failure line, and the hazard records for that file copied from the w4
traces `$PM_WORK/find/R/par{1,2}.trace.jsonl` (header meta `parallel.hazards` and `hazard_rerun`, as the trace lists).

    export PM_WORK=$HOME/pm-p3b; python3 harness/p3b/parallel_only.py --find $PM_WORK/find
"""
from __future__ import annotations

import argparse
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.join(HERE, "data")
OUT = os.path.join(HERE, "PARALLEL-ONLY.md")
REPOS = ["alakajam", "agentlang", "drydock"]
# Explanations the coordinator relayed (recorded as given, dated); the case stays in the list.
EXPLAINED = {
    "server/user/user.service.spec.ts::User service::delete user::should refuse to delete users with entries":
        "explained: engine bug, fixed in parallel-proof-gaps cb42cccf (coordinator, 2026-11-26: pass 2 of a hazard "
        "re-run never rewrote the outcomes file, so par2.outcomes.json kept pass 1's timeout while the trace held the "
        "one-lane re-run's passed record; not a lane-caused flip)",
}


def header_meta(path):
    with open(path) as f:
        for line in f:
            j = json.loads(line)
            if j.get("type") == "header":
                return j.get("meta") or {}
    return {}


def file_hazards(meta, file):
    par = meta.get("parallel") or {}
    hr = meta.get("hazard_rerun")
    out = {"parallel.hazards": [h for h in par.get("hazards") or [] if file in (h.get("a"), h.get("b"))]}
    if hr is None:
        out["hazard_rerun"] = None
    else:
        out["hazard_rerun"] = {
            "present": True, "complete": hr.get("complete"), "reported": hr.get("reported"),
            "file_rerun": file in (hr.get("files") or []),
            "hazards": [h for h in hr.get("hazards") or [] if file in (h.get("a"), h.get("b"))]}
    return out


def test_record(path, tid):
    with open(path) as f:
        for line in f:
            if tid in line:
                j = json.loads(line)
                if j.get("type") == "test" and j.get("nodeid") == tid:
                    return {k: j.get(k) for k in ("outcome", "index", "counts")}
    return None


def collect(find):
    res = []
    for r in REPOS:
        p = os.path.join(DATA, r, "find", "count_extra.json")
        if not os.path.exists(p):
            continue
        ce = json.load(open(p))
        for c in ce.get("parallel_only") or []:
            f = c["id"].split("::", 1)[0]
            runs = []
            for n in (1, 2):
                tp = os.path.join(find, r, f"par{n}.trace.jsonl")
                meta = header_meta(tp)
                tr = test_record(tp, c["id"])
                fh = file_hazards(meta, f)
                if fh["hazard_rerun"] is not None:
                    fh["hazard_rerun"]["in_first_run_failed"] = c["id"] in (meta["hazard_rerun"].get("first_run_failed") or [])
                runs.append({"run": f"par{n}", "trace": tp, "test": tr, "outcomes_file": c["par"][n - 1], **fh})
            res.append({"repo": r, "id": c["id"], "file": f, "w4": c["par"], "first": c.get("first"), "runs": runs})
    return res


def render(cases):
    out = ["# P3b parallel-only cases (generated by `harness/p3b/parallel_only.py`)", "",
           "Failed in one `--det --det-workers=4` run, passed in both plain runs and both w1 `--det` runs. Not run "
           "through the serial ladder and not classified; listed apart and routed to the coordinator for "
           "`claude/parallel-proof-gaps`. They count apart from the serial verdicts.", "",
           "Hazard records: copied from the header `meta` of each w4 trace, filtered to the records naming the case's "
           "file (`parallel.hazards`, and `hazard_rerun` when the trace has one). An empty list is what the trace lists. "
           "Where the outcomes file and the trace's test record disagree, both are shown as recorded; not explained here.",
           "", f"Total: {len(cases)}", "",
           "| repository | test id | w4 run 1 / 2 | first failure line |", "|---|---|---|---|"]
    for c in cases:
        out.append(f"| {c['repo']} | `{c['id']}` | {c['w4'][0]} / {c['w4'][1]} | "
                   f"{(c['first'] or '-').replace('|', '/')[:140]} |")
    for c in cases:
        out += ["", f"## {c['repo']}: `{c['id']}`", "", f"- file: `{c['file']}`",
                f"- w4 outcomes: par1 {c['w4'][0]}, par2 {c['w4'][1]}", f"- first failure line: `{c['first']}`"]
        if c["id"] in EXPLAINED:
            out.append(f"- {EXPLAINED[c['id']]}")
        for run in c["runs"]:
            t = run["test"] or {}
            out += ["", f"{run['run']} (`{run['trace']}`): outcomes file {run['outcomes_file']}; trace test record outcome "
                    f"{t.get('outcome')}, index {t.get('index')}",
                    "", f"- `parallel.hazards` naming the file: {len(run['parallel.hazards'])}"]
            out += [f"  - {json.dumps(h)}" for h in run["parallel.hazards"]]
            hr = run["hazard_rerun"]
            if hr is None:
                out.append("- `hazard_rerun`: not in the trace")
            else:
                out.append(f"- `hazard_rerun`: complete {hr['complete']}, reported {hr['reported']!r}, file re-run {hr['file_rerun']}, "
                           f"case in first_run_failed {hr['in_first_run_failed']}, "
                           f"hazards naming the file: {len(hr['hazards'])}")
                out += [f"  - {json.dumps(h)}" for h in hr["hazards"]]
    return "\n".join(out) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--find", required=True)
    o = ap.parse_args()
    cases = collect(o.find)
    with open(OUT, "w") as fh:
        fh.write(render(cases))
    print(json.dumps({"cases": len(cases), "out": OUT}))


if __name__ == "__main__":
    main()
