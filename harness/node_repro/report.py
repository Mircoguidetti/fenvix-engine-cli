"""Aggregate harness/node_repro/results/<repo>.jsonl (written by run_repro.py) into results/REPORT.md and
results/summary.json.

    python harness/node_repro/report.py

Definitions (per test of the Node Block 1 flaky set that `fenvix repro` was run on):
  attempted          a repro was started on it (the repository was prepared)
  REPRODUCED         status `reproduced`: a failing configuration was found, minimised, and the bundle failed in
                     every one of the 10 confirmation replays with one fingerprint
  cause named        a reproduced bundle whose cause line names something: the polluter(s) (`order`), the state
                     setter(s) (`brittle`), the seed (`fails-alone`: fails alone under one seed, passes under another),
                     or a first divergent event of a controlled source; NOT named: `outcome-only` divergences on a
                     fails-alone bundle and `unknown`
  replay 10/10       the 10 confirmation replays all failed with one fingerprint (== REPRODUCED by construction)
  time per repro     wall-clock seconds of the whole `python -m detpy.fenvix_js repro` process
"""

from __future__ import annotations

import json
import statistics
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import flaky_set  # noqa: E402

RES = HERE / "results"
# not in node-final REPORT.md's 411 Vitest/Jest baseline-unstable tests: its --det runs wrote no trace there
NOT_COUNTED = {"matrix-js-sdk-flaky": "det-no-trace in node-final"}


def cause_class(b: dict) -> str:
    if not b or b.get("status") not in ("reproduced", "replay-unstable"):
        return "-"
    kind = b.get("kind")
    if kind == "order" and b.get("polluters"):
        return "polluter"
    if kind == "brittle" and b.get("setters"):
        return "setter"
    if kind == "uncontrolled":
        return "uncontrolled-source"
    d = b.get("divergence") or {}
    if d.get("reason") and d.get("reason") != "outcome-only":
        return f"event:{d['reason']}"
    if kind == "fails-alone" and not d.get("reason"):
        return "seed"
    return "not-named"


def main() -> int:
    sets = {r["name"]: r for r in flaky_set.repos()}
    rows = []
    replays = {}
    for f in sorted(RES.glob("*.jsonl")):
        for line in f.read_text().splitlines():
            if not line.strip():
                continue
            r = json.loads(line)
            if f.name.endswith(".replay.jsonl"):
                replays[(r["repo"], r["test"])] = r
            else:
                rows.append(r)
    by_repo: dict = {}
    for r in rows:
        by_repo.setdefault(r["repo"], []).append(r)
    total = {"set": sum(len(s["targets"]) for n, s in sets.items() if s["runner"] in ("vitest", "jest")
                        and n not in NOT_COUNTED),
             "set_playwright": sum(len(s["targets"]) for s in sets.values() if s["runner"] == "playwright"), "attempted": 0, "reproduced": 0, "named": 0,
             "replay10": 0, "indep": 0, "indep_ok": 0, "times": [], "runs": [], "block1_reproduced_attempted": 0, "both": 0,
             "not_collected": 0}
    lines = ["# `fenvix repro` on the Node Block 1 flaky set (MEASURED)", "",
             "Generated by `python harness/node_repro/report.py` from `harness/node_repro/results/<repo>.jsonl` "
             "(written by `harness/node_repro/run_repro.py`). Definitions: see the docstring of report.py.", "",
             "| repo | runner | unstable in Block 1 | attempted | REPRODUCED | cause named | replay 10/10 one fp | "
             "Block 1 reproduced (attempted) | median s/repro | median runs | separate `replay` 10/10, bundle fp | causes |",
             "|---|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---|"]
    detail = []
    for name in sorted(by_repo):
        rs = [r for r in by_repo[name] if r.get("test")]
        st = sets.get(name, {"targets": [], "runner": "?", "runner_version": "?"})
        b1 = {t["id"]: t["reproduced_block1"] for t in st["targets"]}
        rep = [r for r in rs if r["status"] == "reproduced"]
        named = [r for r in rep if cause_class(r["bundle"]) not in ("not-named", "-")]
        r10 = [r for r in rs if r.get("bundle") and (r["bundle"].get("replay") or {}).get("fails") == 10
               and (r["bundle"].get("replay") or {}).get("identical_fingerprint")]
        times = [r["wall_s"] for r in rs]
        runs = [r["bundle"].get("runs") for r in rs if r.get("bundle") and r["bundle"].get("runs") is not None]
        causes: dict = {}
        for r in rs:
            c = cause_class(r.get("bundle")) if r["status"] in ("reproduced", "replay-unstable") else r["status"]
            causes[c] = causes.get(c, 0) + 1
        total["attempted"] += len(rs)
        total["not_collected"] += sum(1 for r in rs if r["status"] == "not-collected")
        total["reproduced"] += len(rep)
        total["named"] += len(named)
        total["replay10"] += len(r10)
        total["times"] += times
        total["runs"] += runs
        total["block1_reproduced_attempted"] += sum(1 for r in rs if b1.get(r["test"]))
        total["both"] += sum(1 for r in rep if b1.get(r["test"]))
        ind = [replays[(name, r["test"])] for r in rep if (name, r["test"]) in replays]
        ind_ok = [x for x in ind if x.get("fails") == x.get("runs") == 10 and x.get("identical_fingerprint")
                  and x.get("matches_bundle")]
        total["indep"] += len(ind)
        total["indep_ok"] += len(ind_ok)
        not_prepared = [r for r in by_repo[name] if not r.get("test")]
        lines.append(f"| {name} | {st['runner']} {st['runner_version']} | {len(st['targets'])} | "
                     f"{len(rs)}{' (not prepared)' if not_prepared and not rs else ''} | {len(rep)} | {len(named)} | "
                     f"{len(r10)} | {sum(1 for r in rs if b1.get(r['test']))} | "
                     f"{statistics.median(times) if times else '-'} | {statistics.median(runs) if runs else '-'} | "
                     f"{f'{len(ind_ok)}/{len(ind)}' if ind else '-'} | "
                     f"{', '.join(f'{k} {v}' for k, v in sorted(causes.items()))} |")
        for r in rs:
            b = r.get("bundle") or {}
            rp = b.get("replay") or {}
            detail.append(f"| {name} | `{r['test'][:140]}` | {r['status']} | {cause_class(b)} | "
                          f"{rp.get('fails', '-')}/{rp.get('runs', '-')} {'one fp' if rp.get('identical_fingerprint') else ''} | "
                          f"{b.get('config', '-')} | {len(b.get('order') or [])} | {b.get('runs', '-')} | {r['wall_s']} | "
                          f"{'yes' if b1.get(r['test']) else 'no'} |")
    a = total["attempted"]
    v = a - total["not_collected"]
    pct = lambda n: (f"{n}/{a} = {100 * n / a:.1f}% of attempted, {n}/{v} = {100 * n / v:.1f}% of attempted with a "  # noqa: E731
                     f"stable id" if a and v else "-")
    lines += ["", f"**Totals (MEASURED):** set = {total['set']} Vitest/Jest baseline-unstable tests (node-final "
              f"REPORT.md's 411; Playwright (pw-msw): {total['set_playwright']}; matrix-js-sdk-flaky's "
              f"{len(sets.get('matrix-js-sdk-flaky', {}).get('targets', []))} not counted: "
              f"{NOT_COUNTED['matrix-js-sdk-flaky']}); attempted {a}, of which {total['not_collected']} `not-collected`: ids "
              f"built from run-dependent values (a date, a random number: no later run has that test; node-final "
              f"REPORT.md leaves such ids out of its main metric too); REPRODUCED "
              f"{pct(total['reproduced'])}; cause named {pct(total['named'])}; replay 10/10 with one fingerprint "
              f"{pct(total['replay10'])}; time per repro median "
              f"{statistics.median(total['times']) if total['times'] else '-'} s, mean "
              f"{round(statistics.mean(total['times']), 1) if total['times'] else '-'} s, max "
              f"{max(total['times']) if total['times'] else '-'} s; runner runs per repro median "
              f"{statistics.median(total['runs']) if total['runs'] else '-'}. Block 1 had reproduced "
              f"{total['block1_reproduced_attempted']} of the attempted tests (a seed failing 10/10 and a passing "
              f"--det configuration); repro reproduced {total['both']} of those. Separate `replay --runs 10` of the "
              f"REPRODUCED bundles (fresh process, cleaned tree): {total['indep_ok']}/{total['indep']} failed 10/10 "
              f"with one fingerprint, the bundle's.", "",
              "## Per test", "",
              "| repo | test | status | cause | replays failed | config | bundle order length | runs | wall s | Block 1 reproduced |",
              "|---|---|---|---|---|---|---:|---:|---:|---|", *detail]
    (RES / "REPORT.md").write_text("\n".join(lines) + "\n")
    summ = {k: v for k, v in total.items() if k not in ("times", "runs")}
    summ["median_wall_s"] = statistics.median(total["times"]) if total["times"] else None
    summ["median_runs"] = statistics.median(total["runs"]) if total["runs"] else None
    (RES / "summary.json").write_text(json.dumps(summ, indent=1))
    print("\n".join(lines[:6 + len(by_repo) + 3]))
    return 0


if __name__ == "__main__":
    sys.exit(main())
